export function friendlyName(name: string): string {
  return ELEMENT_INFO[name]?.[0] ?? name.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, (c) => c.toUpperCase());
}

export function elementDescription(name: string): string {
  return ELEMENT_INFO[name]?.[1] ?? '';
}
