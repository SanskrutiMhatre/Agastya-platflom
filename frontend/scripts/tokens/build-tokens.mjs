// Generate src/styles/tokens/tokens.css from src/styles/tokens/tokens.json (audit WP-19, DS-001).
//   node scripts/tokens/build-tokens.mjs           write tokens.css
//   node scripts/tokens/build-tokens.mjs --check   exit 1 when tokens.css is not what the source generates (CI)
import fs from 'node:fs';
import { OUTPUT, readSource, validateSource } from './lib.mjs';

const s = readSource();
const errors = validateSource(s);
if (errors.length) { console.error(`tokens.json has ${errors.length} problem(s):\n  ${errors.join('\n  ')}`); process.exit(1); }

const known = new Set([...Object.keys(s.semantic), ...Object.keys(s.fixed), ...Object.keys(s.scale), ...Object.keys(s.density.comfortable)]);
const prim = (v) => `var(--p-${v.slice(1, -1)})`;
const decl = (k, v) => `  --${k}: ${v};`;
const block = (sel, lines) => `${sel} {\n${lines.join('\n')}\n}\n`;

const light = [], dark = [];
for (const [k, [l, d]] of Object.entries(s.semantic)) {
  const over = s.accentOverride.includes(k);
  light.push(decl(k, over ? `var(--admin-${k}-light, ${prim(l)})` : prim(l)));
  dark.push(decl(k, over ? `var(--admin-${k}-dark, ${prim(d)})` : prim(d)));
}

const css = [
  '/* GENERATED by scripts/tokens/build-tokens.mjs from tokens.json - do not edit by hand.',
  '   Three tiers: --p-* primitives (raw values), semantic tokens (light here, dark below; `fixed` ones are the same in both themes),',
  '   then the alias tier (component and legacy names). The only colour literals of the application live in this file. */',
  block(':root', [
    '  /* primitive */', ...Object.entries(s.primitive).map(([k, v]) => decl(`p-${k}`, v)),
    '  /* scale */', ...Object.entries(s.scale).map(([k, v]) => decl(k, v)),
    '  /* density: comfortable (default) */', ...Object.entries(s.density.comfortable).map(([k, v]) => decl(k, v)),
    '  /* fixed: the same in both themes */', ...Object.entries(s.fixed).map(([k, v]) => decl(k, prim(v))),
    '  /* semantic: light */', ...light,
    '  /* alias */', ...Object.entries(s.alias).map(([k, v]) => decl(k, known.has(v) ? `var(--${v})` : v)),
    '  color-scheme: light;',
  ]),
  block(":root[data-theme='dark']", ['  /* semantic: dark */', ...dark, '  color-scheme: dark;']),
  block("html.v2-compact, [data-density='compact']", Object.entries(s.density.compact).map(([k, v]) => decl(k, v))),
  block("[data-density='comfortable']", Object.entries(s.density.comfortable).map(([k, v]) => decl(k, v))),
].join('\n').replace(/\r?\n/g, '\r\n');

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (cur !== css) { console.error('tokens.css is out of date: run node scripts/tokens/build-tokens.mjs'); process.exit(1); }
  console.log('tokens.css is up to date');
} else {
  fs.writeFileSync(OUTPUT, css);
  console.log(`wrote ${OUTPUT} (${Object.keys(s.primitive).length} primitives, ${Object.keys(s.semantic).length} semantic, ${Object.keys(s.fixed).length} fixed, ${Object.keys(s.alias).length} aliases)`);
}
