// ── assisted assignment ──────────────────────────────────────────────────

const entryOf = (dmc) => {
  const [model, sd, sys, subsub, assy, dis, info, loc] = dmc.split('-');
  return { type: 'dm', dmCode: { modelIdentCode: model, systemDiffCode: sd, systemCode: sys, subSystemCode: subsub[0], subSubSystemCode: subsub[1], assyCode: assy, disassyCode: dis.slice(0, 2), disassyCodeVariant: dis.slice(2), infoCode: info.slice(0, 3), infoCodeVariant: info.slice(3), itemLocationCode: loc }, techName: dmc };
};
const place = (dmc, file = `${dmc}.xml`) => ({ file, key: dmc.toUpperCase(), entry: entryOf(dmc) });
const tree = () => [
  { type: 'folder', title: 'Chapter 1', children: [entryOf(M1)] },
  { type: 'pmRef', title: "Annexure 'A' - Radar manual", pmCode: pm('00010'), pmTitle: 'Radar manual' },
];

test('assign: modules go into the chosen folder; a module already placed is refused unless reuse is set', () => {
  const r = assignToTree(tree(), [place(M2), place(M1)], { folderPath: [0] }, { reuse: false });
  assert.deepEqual(r.placed, [`${M2}.xml`]);
  assert.equal(r.refused.length, 1);
  assert.match(r.refused[0].reason, /already placed/);
  assert.equal(r.entries[0].children.length, 2);
  const again = assignToTree(tree(), [place(M1)], { folderPath: [0] }, { reuse: true });
  assert.equal(again.entries[0].children.length, 2, 'reuse: the same module may stand in two places');
  assert.equal(tree()[0].children.length, 1, 'the input tree is never mutated');
});

test('assign: a bare pmRef becomes a folder with the anchor first; a second step finds the same folder again', () => {
  const o = outline(tree());
  assert.ok(o.some((n) => n.kind === 'pmRef' && n.pmCode === key(pm('00010'))), 'the screen can offer the sub-publication as a target');
  const first = assignToTree(tree(), [place(A1)], { subPublication: key(pm('00010')) }, { reuse: false, anchor: place(TA) });
  assert.equal(first.materialised.title, "Annexure 'A' - Radar manual");
  const folder = first.entries[1];
  assert.equal(folder.type, 'folder');
  assert.deepEqual(folder.children.map((c) => c.techName), [TA, A1], 'anchor first, then what was assigned');
  const second = assignToTree(first.entries, [place(A2)], { subPublication: key(pm('00010')) }, { reuse: false, anchor: place(TA), materialisedTitle: first.materialised.title });
  assert.deepEqual(second.entries[1].children.map((c) => c.techName), [TA, A1, A2], 'no second anchor, no second folder');
  assert.equal(second.materialised, undefined);
});

test('assign: a new folder can be made; unknown folders and sub-publications are 404s, an empty result is refused', () => {
  const r = assignToTree(tree(), [place(M2)], { folderPath: [], newFolder: 'Extras' }, { reuse: false });
  assert.equal(r.entries[r.entries.length - 1].title, 'Extras');
  assert.throws(() => assignToTree(tree(), [place(M2)], { folderPath: [7] }, { reuse: false }), /no folder/i);
  assert.throws(() => assignToTree(tree(), [place(M2)], { subPublication: 'TST-1671Y-99999-00' }, { reuse: false }), /not a reference/i);
  assert.throws(() => assignToTree(tree(), [place(M1)], { folderPath: [0] }, { reuse: false }), /Nothing to place/);
  assert.ok(placedIn(tree()).keys.has(M1.toUpperCase()));
});

